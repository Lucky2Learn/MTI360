    assert sanitize_file_name("re\u0000port\u202e.pdf") == "report.pdf"
    assert sanitize_file_name('a<b>"c|d.pdf') == "a_b__c_d.pdf"
    long = sanitize_file_name("x" * 500 + ".pdf")
    assert long is not None
    assert len(long) == FILE_NAME_MAX_LENGTH
    assert long.endswith(".pdf")


