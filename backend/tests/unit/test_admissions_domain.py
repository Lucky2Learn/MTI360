    assert sanitize_file_name("C:\\Users\\arjun\\cdc.jpg") == "cdc.jpg"
    assert sanitize_file_name("../../etc/marks.png") == "marks.png"
    assert sanitize_file_name("..") is None
    assert sanitize_file_name(".pdf") is None
