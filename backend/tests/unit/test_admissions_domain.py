# --- Upload validation ---------------------------------------------------------------------

PNG = b"\x89PNG\r\n\x1a\n" + b"\x00" * 32
JPEG = b"\xff\xd8\xff\xe0" + b"\x00" * 32


def pdf(*objects: bytes) -> bytes:
    body = b"\n".join(objects)
    return b"%PDF-1.7\n" + body + b"\ntrailer\n<< /Root 1 0 R >>\n%%EOF\n"


PLAIN_PDF = pdf(b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj")


def object_stream(payload: bytes) -> bytes:
    compressed = zlib.compress(payload)
    return (
        b"5 0 obj\n<< /Type /ObjStm /N 1 /First 4 /Filter /FlateDecode /Length "
        + str(len(compressed)).encode()
        + b" >>\nstream\n"
        + compressed
        + b"\nendstream\nendobj"
    )


