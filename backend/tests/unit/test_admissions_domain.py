def test_review_moves_pair_by_pair() -> None:
    decisions = {S.APPROVED, S.CORRECTION_REQUIRED, S.REJECTED, S.NOT_ELIGIBLE}
    expected = {
        S.SUBMITTED: decisions | {S.UNDER_REVIEW},
        S.UNDER_REVIEW: decisions,
    }
    for source, target in itertools.product(ApplicationStatus, repeat=2):
        allowed = target in expected.get(source, set())
        assert REVIEW_TRANSITIONS.allows(source, target) is allowed, (source, target)
    # Reviewers never set ADMITTED, the reserved statuses, or go back to a draft.
    reachable = {t for s in ApplicationStatus for t in REVIEW_TRANSITIONS.targets(s)}
    assert not reachable & {S.ADMITTED, S.DRAFT, S.DOCUMENT_VERIFICATION, S.ELIGIBLE}


def test_review_problems() -> None:
    assert review_problem(S.DRAFT, S.APPROVED, reason=None, unverified_documents=0) is (
        ReviewProblem.INVALID
    )
    for target in (S.CORRECTION_REQUIRED, S.REJECTED, S.NOT_ELIGIBLE):
        assert review_problem(S.SUBMITTED, target, reason=None, unverified_documents=0) is (
            ReviewProblem.REASON_REQUIRED
        )
        assert review_problem(S.SUBMITTED, target, reason="x", unverified_documents=3) is None
    assert review_problem(S.UNDER_REVIEW, S.APPROVED, reason=None, unverified_documents=1) is (
        ReviewProblem.DOCUMENTS_PENDING
    )
    # No checklist (Y4): an application without pending documents may be approved.
    assert review_problem(S.UNDER_REVIEW, S.APPROVED, reason=None, unverified_documents=0) is None
    assert review_problem(S.SUBMITTED, S.UNDER_REVIEW, reason=None, unverified_documents=2) is None


